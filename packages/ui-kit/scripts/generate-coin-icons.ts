//* Writes the coin icon indexes under `src/coin-icons/generated` from web3icons' token metadata:
//* icon loaders by symbol, and icon symbols by contract address for each token network. Both are
//* split into shards (`src/coin-icons/shards.ts`), loaded only when a lookup needs them.
//*
//! The output must be reformatted by `oxfmt` in a following call.

import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { tokens, type ITokenMetadata } from "@web3icons/common"

import { getAddressShard, getSymbolShard, normalizeTokenAddress } from "../src/coin-icons/shards"

const PACKAGE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const OUTPUT_ROOT = join(PACKAGE_ROOT, "src/coin-icons/generated")
const ICONS_PACKAGE = "@web3icons/react"
const EVM_ADDRESS = /^0x[0-9a-f]{40}$/u
const TRON_ADDRESS = /^T[1-9A-HJ-NP-Za-km-z]{33}$/u

//* web3icons keys token addresses by CoinGecko platform id; checkouts identify a network by its
//* CAIP-2 id.
const NETWORKS_BY_PLATFORM: Record<string, { network: string; address: RegExp }> = {
  ethereum: { network: "eip155:1", address: EVM_ADDRESS },
  "binance-smart-chain": { network: "eip155:56", address: EVM_ADDRESS },
  "polygon-pos": { network: "eip155:137", address: EVM_ADDRESS },
  tron: { network: "tron:728126428", address: TRON_ADDRESS },
}

const HEADER = `//! Generated by scripts/generate-coin-icons.ts from @web3icons/common. Do not edit.\n`

const iconsDistRoot = dirname(fileURLToPath(import.meta.resolve(ICONS_PACKAGE)))

//* Mirrors `getIconKey` in web3icons' `utils/loadIcon.js`, which names the module of an icon.
const toPascalCase = (name: string) =>
  (name.match(/[a-z0-9]+/giu) ?? [])
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join("")

const getIconModule = ({ filePath }: ITokenMetadata) => {
  const [type = "", name = ""] = filePath.split(":")

  if (type === "token") {
    return `icons/tokens/Token${name.replace(/[- ]+/gu, "_").toUpperCase()}`
  } else if (type === "network") {
    return `icons/networks/Network${toPascalCase(name)}`
  } else return null
}

const groupBy = <T>(entries: [string, T][], getShard: (key: string) => string) => {
  const shards = new Map<string, [string, T][]>()

  for (const entry of entries) {
    const shard = getShard(entry[0])

    shards.set(shard, [...(shards.get(shard) ?? []), entry])
  }

  return shards
}

//* By code point, not by locale, so the output is the same on every machine. Keys are unique.
const sorted = <T>(entries: Iterable<[string, T]>) =>
  [...entries].toSorted(([a], [b]) => (a < b ? -1 : 1))

const toObjectLiteral = (entries: [string, string][]) =>
  `{\n${entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${value},`).join("\n")}\n}`

const failures: string[] = []
const modulesBySymbol = new Map<string, string>()

//! A symbol or an address shared by two tokens would give one of them the other's icon, so both
//! must stay unique.
for (const token of tokens) {
  const iconModule = getIconModule(token)
  const symbol = token.symbol.toUpperCase()

  if (iconModule === null) {
    failures.push(`${token.id}: unknown icon type in "${token.filePath}"`)
  } else if (!existsSync(join(iconsDistRoot, `${iconModule}.js`))) {
    failures.push(`${token.id}: ${ICONS_PACKAGE}/${iconModule} does not exist`)
  } else if (modulesBySymbol.has(symbol)) {
    failures.push(`${token.id}: another token already uses the symbol ${symbol}`)
  } else modulesBySymbol.set(symbol, iconModule)
}

const networks = Object.entries(NETWORKS_BY_PLATFORM).map(([platform, { network, address }]) => {
  const symbolsByAddress = new Map<string, string>()

  for (const token of tokens) {
    const tokenAddress = token.addresses[platform]

    const key =
      tokenAddress === undefined ? undefined : normalizeTokenAddress(network, tokenAddress)

    if (key !== undefined && !address.test(key)) {
      failures.push(`${token.id}: "${key}" on ${platform} is not a ${network} address`)
    } else if (key !== undefined && symbolsByAddress.has(key)) {
      failures.push(`${token.id}: another token already uses ${key} on ${platform}`)
    } else if (key !== undefined) symbolsByAddress.set(key, token.symbol.toUpperCase())
  }

  return { platform, network, shards: groupBy(sorted(symbolsByAddress), getAddressShard) }
})

const iconShards = groupBy(sorted(modulesBySymbol), getSymbolShard)

const files = new Map<string, string>([
  [
    "icons.generated.ts",
    `${HEADER}
import type { CoinIconShard } from "@/coin-icons/types"

export const iconShardLoaders: Record<string, () => Promise<CoinIconShard>> = ${toObjectLiteral(
      sorted(iconShards).map(([shard]) => [shard, `() => import("./icons/${shard}.generated")`]),
    )}
`,
  ],

  ...sorted(iconShards).map(([shard, entries]): [string, string] => [
    `icons/${shard}.generated.ts`,
    `${HEADER}
import type { CoinIconModule } from "@/coin-icons/types"

export const iconLoadersBySymbol: Record<string, () => Promise<CoinIconModule>> = ${toObjectLiteral(
      entries.map(([symbol, iconModule]) => [
        symbol,
        `() => import("${ICONS_PACKAGE}/${iconModule}")`,
      ]),
    )}
`,
  ]),

  [
    "networks.generated.ts",
    `${HEADER}
import type { CoinIconAddressShard } from "@/coin-icons/types"

export const addressShardLoadersByNetwork: Record<
  string,
  Record<string, () => Promise<CoinIconAddressShard>>
> = {
${networks
  .map(
    ({ platform, network, shards }) =>
      `  ${JSON.stringify(network)}: ${toObjectLiteral(
        sorted(shards).map(([shard]) => [
          shard,
          `() => import("./${platform}/${shard}.generated")`,
        ]),
      )},`,
  )
  .join("\n")}
}
`,
  ],

  ...networks.flatMap(({ platform, shards }) =>
    sorted(shards).map(([shard, entries]): [string, string] => [
      `${platform}/${shard}.generated.ts`,
      `${HEADER}
export const symbolsByAddress: Record<string, string> = ${toObjectLiteral(
        entries.map(([address, symbol]) => [address, JSON.stringify(symbol)]),
      )}
`,
    ]),
  ),
])

const listFiles = (directory: string): string[] =>
  readdirSync(directory, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? listFiles(join(directory, entry.name))
      : [relative(OUTPUT_ROOT, join(directory, entry.name))],
  )

if (failures.length > 0) {
  for (const failure of failures) {
    console.error(`coin-icons: ${failure}`)
  }

  console.error("coin-icons: no index was written; resolve the conflicts above first.")
  process.exit(1)
} else {
  for (const [path, source] of files) {
    mkdirSync(dirname(join(OUTPUT_ROOT, path)), { recursive: true })
    writeFileSync(join(OUTPUT_ROOT, path), source)
  }

  for (const stale of listFiles(OUTPUT_ROOT).filter((path) => !files.has(path))) {
    rmSync(join(OUTPUT_ROOT, stale))
  }

  console.log(
    `coin-icons: ${modulesBySymbol.size} symbols; ${networks
      .map(({ platform, shards }) => {
        const addresses = [...shards.values()].reduce((count, entries) => count + entries.length, 0)

        return `${addresses} ${platform} addresses`
      })
      .join(", ")}`,
  )
}
